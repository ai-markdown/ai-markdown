  'interface RetryOptions {',
  '  /** Attempts before the last error is thrown. */',
  '  attempts: number;',
  '  /** Delay before the second attempt, in milliseconds. */',
  '  baseDelay: number;',
  '  /** Upper bound of one delay, in milliseconds. */',
  '  maxDelay: number;',
  '  /** Stops the loop between attempts. */',
  '  signal?: AbortSignal;',
  '}',
  '',
  'const wait = (ms: number, signal?: AbortSignal) =>',
  '  new Promise<void>((resolve, reject) => {',
  '    const timer = setTimeout(resolve, ms);',
  '    signal?.addEventListener(',
  "      'abort',",
  '      () => {',
  '        clearTimeout(timer);',
  '        reject(signal.reason);',
  '      },',
  '      { once: true }',
  '    );',
  '  });',
  '',
  'export async function retry<T>(task: () => Promise<T>, options: RetryOptions): Promise<T> {',
  '  let failure: unknown;',
  '  for (let attempt = 0; attempt < options.attempts; attempt++) {',
  '    options.signal?.throwIfAborted();',
  '    try {',
  '      return await task();',
  '    } catch (error) {',
  '      failure = error;',
  '      const delay = Math.min(options.maxDelay, options.baseDelay * 2 ** attempt);',
  '      if (attempt + 1 < options.attempts) await wait(delay, options.signal);',
  '    }',
  '  }',
  '  throw failure;',
  '}',
  '```',
